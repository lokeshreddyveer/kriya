        assert!(
            looks_sensitive("4111 1111 1111 1111"),
            "a valid card number"
        );
        assert!(
            !looks_sensitive("4111 1111 1111 1112"),
            "fails the check digit"
        );
        assert!(looks_sensitive("ghp_abcdefghijklmnopqrstuvwxyz0123456789"));
        assert!(looks_sensitive("AKIAIOSFODNN7EXAMPLE"));
