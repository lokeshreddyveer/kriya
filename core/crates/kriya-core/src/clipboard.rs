#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize, uniffi::Enum)]
#[serde(rename_all = "snake_case")]
pub enum ClipKind {
    Text,
    RichText,
    Image,
    Files,
    Url,
}

impl ClipKind {
    pub fn as_str(self) -> &'static str {
        match self {
            ClipKind::Text => "text",
            ClipKind::RichText => "rich_text",
            ClipKind::Image => "image",
            ClipKind::Files => "files",
            ClipKind::Url => "url",
        }
    }

    pub fn parse(s: &str) -> Option<Self> {
        Some(match s {
            "text" => ClipKind::Text,
            "rich_text" => ClipKind::RichText,
            "image" => ClipKind::Image,
            "files" => ClipKind::Files,
            "url" => ClipKind::Url,
            _ => return None,
        })
    }
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, uniffi::Record)]
#[serde(default)]
pub struct ClipConfig {
    /// Stop recording. What is already saved stays.
    pub paused: bool,
    /// Most items kept, not counting pinned items and snippets.
    pub max_items: u32,
    /// Items older than this many days are removed (pinned items and snippets stay). 0 keeps them for ever.
    pub retention_days: u32,
    /// Largest single item recorded, in megabytes.
    pub max_item_mb: u32,
    /// Most the history may take up in total, in megabytes.
    pub max_total_mb: u32,
    pub capture_text: bool,
    pub capture_rich_text: bool,
    pub capture_images: bool,
    pub capture_files: bool,
    /// Leave out text that looks like a password, key or card number.
    pub skip_secrets: bool,
    pub excluded_app_ids: Vec<String>,
    /// Shortcuts: the quick-access window, paste as plain text, and remove formatting from the clipboard.
    pub quick_key: Option<u16>,
    pub quick_modifiers: u64,
    pub plain_key: Option<u16>,
    pub plain_modifiers: u64,
    pub strip_key: Option<u16>,
    pub strip_modifiers: u64,
    /// Paste into the app in front after choosing an item (needs Accessibility). Otherwise it is only copied.
    pub auto_paste: bool,
}

impl Default for ClipConfig {
    fn default() -> Self {
        ClipConfig {
            paused: false,
            max_items: 500,
            retention_days: 30,
            max_item_mb: 20,
            max_total_mb: 512,
            capture_text: true,
            capture_rich_text: true,
            capture_images: true,
            capture_files: true,
            skip_secrets: true,
            excluded_app_ids: DEFAULT_EXCLUDED_APPS
                .iter()
                .map(|s| (*s).to_string())
                .collect(),
            quick_key: Some(9),
            quick_modifiers: m::CONTROL | m::OPTION,
            plain_key: Some(9),
            plain_modifiers: m::CONTROL | m::OPTION | m::SHIFT,
            strip_key: None,
            strip_modifiers: 0,
            auto_paste: true,
        }
    }
}

impl ClipConfig {
    pub fn sanitized(mut self) -> Self {
        self.max_items = self.max_items.clamp(20, 10_000);
        self.retention_days = self.retention_days.min(3650);
        self.max_item_mb = self.max_item_mb.clamp(1, 500);
        self.max_total_mb = self.max_total_mb.clamp(16, 50_000);
        let mut seen = HashSet::new();
        self.excluded_app_ids = self
            .excluded_app_ids
            .iter()
            .map(|a| a.trim().to_string())
            .filter(|a| !a.is_empty() && seen.insert(a.clone()))
            .collect();
        for (key, mods) in [
            (&mut self.quick_key, &mut self.quick_modifiers),
            (&mut self.plain_key, &mut self.plain_modifiers),
            (&mut self.strip_key, &mut self.strip_modifiers),
        ] {
            *mods &= m::ALL;
            // A shortcut with no modifier keys would take over normal typing.
            if *mods == 0 {
                *key = None;
            }
        }
        self
    }

    pub fn is_excluded(&self, app_id: Option<&str>) -> bool {
        app_id.is_some_and(|a| self.excluded_app_ids.iter().any(|x| x == a))
    }

    pub fn max_item_bytes(&self) -> u64 {
        u64::from(self.max_item_mb) * 1024 * 1024
    }

    pub fn max_total_bytes(&self) -> u64 {
        u64::from(self.max_total_mb) * 1024 * 1024
    }

    /// Two shortcuts on the same keys cannot both work.
    pub fn shortcut_problem(&self) -> Option<String> {
        let list = [
            ("quick access", self.quick_key, self.quick_modifiers),
            ("paste as plain text", self.plain_key, self.plain_modifiers),
            ("remove formatting", self.strip_key, self.strip_modifiers),
        ];
        for (i, a) in list.iter().enumerate() {
            for b in &list[i + 1..] {
                if a.1.is_some() && a.1 == b.1 && a.2 == b.2 {
                    return Some(format!("“{}” and “{}” use the same keys", a.0, b.0));
                }
            }
        }
        None
    }
}

/// One thing that was copied, as the shell reports it.
#[derive(Debug, Clone, PartialEq, Default, uniffi::Record)]
pub struct NewClip {
    pub text: Option<String>,
    /// Formatted text (RTF or HTML) that came with the plain text.
    pub rich: Option<Vec<u8>>,
    pub rich_format: Option<String>,
    pub image: Option<Vec<u8>>,
    pub image_format: Option<String>,
    pub image_width: Option<u32>,
    pub image_height: Option<u32>,
    pub files: Vec<String>,
    pub source_app: Option<String>,
    /// The copy carried a "concealed" or "transient" marker.
    pub concealed: bool,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, uniffi::Enum)]
#[serde(rename_all = "snake_case")]
pub enum ClipSkipReason {
    Paused,
    Concealed,
    ExcludedApp,
    LooksSensitive,
    TooLarge,
    TypeTurnedOff,
    Empty,
}

impl NewClip {
    pub fn kind(&self) -> Option<ClipKind> {
        if !self.files.is_empty() {
            return Some(ClipKind::Files);
        }
        if let Some(text) = &self.text {
            if !text.trim().is_empty() {
                return Some(if self.rich.as_ref().is_some_and(|r| !r.is_empty()) {
                    ClipKind::RichText
                } else {
                    classify_text(text)
                });
            }
        }
        if self.image.as_ref().is_some_and(|i| !i.is_empty()) {
            return Some(ClipKind::Image);
        }
        None
    }

    pub fn byte_size(&self) -> u64 {
        let text = self.text.as_ref().map_or(0, String::len);
        let rich = self.rich.as_ref().map_or(0, Vec::len);
        let image = self.image.as_ref().map_or(0, Vec::len);
        let files: usize = self.files.iter().map(String::len).sum();
        (text + rich + image + files) as u64
    }
}

/// A single-line web or mail address is a link; everything else is text.
pub fn classify_text(text: &str) -> ClipKind {
    let t = text.trim();
    if t.is_empty() || t.contains(char::is_whitespace) || t.len() > 2048 {
        return ClipKind::Text;
    }
    match url::Url::parse(t) {
        Ok(u)
            if matches!(u.scheme(), "http" | "https" | "ftp" | "mailto")
                && (u.has_host() || u.scheme() == "mailto") =>
        {
            ClipKind::Url
        }
        _ => ClipKind::Text,
    }
}

/// Whether text looks like something that should not be kept: a private key, a card number, or a token.
pub fn looks_sensitive(text: &str) -> bool {
    let t = text.trim();
    if t.is_empty() {
        return false;
    }
    if t.contains("-----BEGIN ") && t.contains("PRIVATE KEY") {
        return true;
    }
    if t.len() > 300 || t.contains(char::is_whitespace) {
        // A card number may be written with spaces; nothing else long or spread out is treated as a secret.
        return is_card_number(t);
    }
    if is_card_number(t) {
        return true;
    }
    const PREFIXES: [&str; 14] = [
        "sk-",
        "sk_live_",
        "sk_test_",
        "pk_live_",
        "ghp_",
        "gho_",
        "ghs_",
        "github_pat_",
        "xoxb-",
        "xoxp-",
        "AKIA",
        "ASIA",
        "AIza",
        "glpat-",
    ];
    if PREFIXES.iter().any(|p| t.starts_with(p)) && t.len() >= 16 {
        return true;
    }
    if is_jwt(t) {
        return true;
    }
    looks_like_random_token(t)
}

fn is_card_number(t: &str) -> bool {
    if !t
        .chars()
        .all(|c| c.is_ascii_digit() || c == ' ' || c == '-')
    {
        return false;
    }
    let digits: Vec<u32> = t.chars().filter_map(|c| c.to_digit(10)).collect();
    if !(13..=19).contains(&digits.len()) {
        return false;
    }
    let sum: u32 = digits
        .iter()
        .rev()
        .enumerate()
        .map(|(i, d)| {
            if i % 2 == 1 {
                let x = d * 2;
                if x > 9 {
                    x - 9
                } else {
                    x
                }
            } else {
                *d
            }
        })
        .sum();
    sum.is_multiple_of(10)
}

fn is_jwt(t: &str) -> bool {
    let parts: Vec<&str> = t.split('.').collect();
    parts.len() == 3
        && t.starts_with("eyJ")
        && parts.iter().all(|p| {
            p.len() >= 8
                && p.chars()
                    .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_' || c == '=')
        })
}

/// A long run of mixed letters, digits and symbols with no words in it, such as a generated password or API key.
fn looks_like_random_token(t: &str) -> bool {
    if t.len() < 20
        || t.len() > 200
        || t.contains("://")
        || t.contains('/') && t.matches('/').count() > 2
    {
        return false;
    }
    let lower = t.chars().any(|c| c.is_ascii_lowercase());
    let upper = t.chars().any(|c| c.is_ascii_uppercase());
    let digit = t.chars().any(|c| c.is_ascii_digit());
    let symbol = t.chars().any(|c| !c.is_alphanumeric());
    let classes = u8::from(lower) + u8::from(upper) + u8::from(digit) + u8::from(symbol);
    if classes < 3 {
        return false;
    }
    entropy_bits_per_char(t) > 3.7
}

fn entropy_bits_per_char(t: &str) -> f64 {
    let mut counts = std::collections::HashMap::new();
    let mut total = 0.0;
    for c in t.chars() {
        *counts.entry(c).or_insert(0.0) += 1.0;
        total += 1.0;
    }
    counts
        .values()
        .map(|n| {
            let p: f64 = n / total;
            -p * p.log2()
        })
        .sum()
}

/// Why a copy should not be recorded, or `None` to record it.
pub fn should_skip(new: &NewClip, config: &ClipConfig) -> Option<ClipSkipReason> {
    if config.paused {
        return Some(ClipSkipReason::Paused);
    }
    if new.concealed {
        return Some(ClipSkipReason::Concealed);
    }
    if config.is_excluded(new.source_app.as_deref()) {
        return Some(ClipSkipReason::ExcludedApp);
    }
    let Some(kind) = new.kind() else {
        return Some(ClipSkipReason::Empty);
    };
    let allowed = match kind {
        ClipKind::Text | ClipKind::Url => config.capture_text,
        ClipKind::RichText => config.capture_text && config.capture_rich_text,
        ClipKind::Image => config.capture_images,
        ClipKind::Files => config.capture_files,
    };
    if !allowed {
        // Formatted text can still be kept as plain text when only the formatting is turned off.
        if !(kind == ClipKind::RichText && config.capture_text) {
            return Some(ClipSkipReason::TypeTurnedOff);
        }
    }
    if new.byte_size() > config.max_item_bytes() {
        return Some(ClipSkipReason::TooLarge);
    }
    if config.skip_secrets
        && matches!(kind, ClipKind::Text | ClipKind::RichText)
        && new.text.as_deref().is_some_and(looks_sensitive)
    {
        return Some(ClipSkipReason::LooksSensitive);
    }
    None
}

/// A fingerprint of what was copied. The same copy twice has the same fingerprint, which is how duplicates are found.
pub fn content_hash(new: &NewClip) -> String {
    let mut hasher = Sha256::new();
    match new.kind() {
        Some(ClipKind::Files) => {
            let mut files = new.files.clone();
            files.sort();
            hasher.update(b"files\0");
            hasher.update(files.join("\n").as_bytes());
        }
        Some(ClipKind::Image) => {
            hasher.update(b"image\0");
            hasher.update(new.image.as_deref().unwrap_or_default());
        }
        _ => {
            hasher.update(b"text\0");
            hasher.update(new.text.as_deref().unwrap_or_default().as_bytes());
            if let Some(rich) = &new.rich {
                hasher.update(b"\0rich\0");
                hasher.update(rich);
            }
        }
    }
    hasher
        .finalize()
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect()
}

/// A short readable form for lists: the first part of the text, the file names, or a description of the image.
pub fn make_preview(new: &NewClip) -> String {
    match new.kind() {
        Some(ClipKind::Files) => {
            let names: Vec<String> = new
                .files
                .iter()
                .map(|f| crate::finder::file_name(f))
                .collect();
            truncate(&names.join(", "), MAX_PREVIEW_CHARS)
        }
        Some(ClipKind::Image) => match (new.image_width, new.image_height) {
            (Some(w), Some(h)) => format!("Image, {w} × {h}"),
            _ => "Image".to_string(),
        },
        _ => truncate(
            &collapse_whitespace(new.text.as_deref().unwrap_or_default()),
            MAX_PREVIEW_CHARS,
        ),
    }
}

fn truncate(s: &str, limit: usize) -> String {
    if s.chars().count() <= limit {
        return s.to_string();
    }
    let mut out: String = s.chars().take(limit).collect();
    out.push('…');
    out
}

fn collapse_whitespace(s: &str) -> String {
    let mut out = String::with_capacity(s.len().min(MAX_PREVIEW_CHARS * 2));
    let mut space = false;
    for c in s.trim().chars() {
        if c.is_whitespace() {
            space = true;
        } else {
            if space && !out.is_empty() {
                out.push(' ');
            }
            space = false;
            out.push(c);
        }
        if out.chars().count() > MAX_PREVIEW_CHARS * 2 {
            break;
        }
    }
    out
}

/// The lower-case text a search looks through.
pub fn make_search_text(new: &NewClip, title: Option<&str>) -> String {
    let mut text = String::new();
    if let Some(t) = title {
        text.push_str(t);
        text.push('\n');
    }
    match new.kind() {
        Some(ClipKind::Files) => text.push_str(&new.files.join("\n")),
        Some(ClipKind::Image) => text.push_str("image picture screenshot"),
        _ => text.push_str(new.text.as_deref().unwrap_or_default()),
    }
    if let Some(app) = &new.source_app {
        text.push('\n');
        text.push_str(app);
    }
    text.chars()
        .take(MAX_SEARCH_CHARS)
        .collect::<String>()
        .to_lowercase()
}

/// Tidies a list of tags: trimmed, lower case, no repeats, no commas, a sensible length and number.
pub fn clean_tags(tags: &[String]) -> Vec<String> {
    let mut seen = HashSet::new();
    tags.iter()
        .map(|t| {
            t.trim()
                .trim_start_matches('#')
                .replace(',', " ")
                .trim()
                .to_lowercase()
        })
        .filter(|t| !t.is_empty() && t.chars().count() <= MAX_TAG_CHARS && seen.insert(t.clone()))
        .take(MAX_TAGS)
        .collect()
}

