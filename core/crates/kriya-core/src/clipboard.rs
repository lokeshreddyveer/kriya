//! Clipboard history rules shared by every platform: what counts as a copy, what to leave out (passwords, secrets,
//! excluded apps), how copies are told apart, and the settings. Storage is in `clipboard_db.rs`. Nothing here touches
//! the system clipboard or the network; history stays on the device.

